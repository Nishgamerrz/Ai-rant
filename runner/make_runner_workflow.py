#!/usr/bin/env python3
"""Build the tiny public "shell" workflow that runs this repo's pipeline.

Why this exists
---------------
GitHub Actions on a **private** repository draws on the account's paid/free
minutes, and a 1h20 run burns them fast. Public repositories get free standard
runners - but a public repository shows every file in it.

So the code stays private and only a two-screen shell goes public: a repository
whose single file is `.github/workflows/main.yml`. That shell checks this private
repository out into `src/`, then runs exactly the same steps as
`.github/workflows/main.yml` from inside `src/`. Nothing else is copied: no tools,
no prompts module, no users/ models.

`python3 runner/make_runner_workflow.py` regenerates `runner/main.yml`, and
`tests/test_runner_shell.py` fails if the two ever drift apart.
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / ".github" / "workflows" / "main.yml"
TARGET = ROOT / "runner" / "main.yml"
PRIVATE_REPO = "Nishgamerrz/Ai-rant"
SOURCE_DIR = "src"

BANNER = """\
# ---------------------------------------------------------------------------
# PUBLIC SHELL - this is the only file in this repository.
#
# The generator itself (tools/, users/, prompts) is private and is checked out
# into the folder "src" by the first step below, with a read-only token stored as
# the secret SOURCE_TOKEN. Every step then runs inside src, exactly as it does in
# the private repository, so the pipeline output is identical.
#
# Generated by runner/make_runner_workflow.py - edit the private repository's
# .github/workflows/main.yml and regenerate instead of editing this file.
# ---------------------------------------------------------------------------
"""

CHECKOUT = f"""      - name: Check out the private generator (read-only)
        uses: actions/checkout@v4
        with:
          repository: {PRIVATE_REPO}
          token: ${{{{ secrets.SOURCE_TOKEN }}}}
          path: {SOURCE_DIR}
"""

DEFAULTS = f"""    defaults:
      run:
        working-directory: {SOURCE_DIR}
"""


def _prefix_paths(text: str) -> str:
    """Point every repo-relative path at the checked-out src/ folder."""
    text = text.replace(
        "cache-dependency-path: tools/video_renderer/package-lock.json",
        f"cache-dependency-path: {SOURCE_DIR}/tools/video_renderer/package-lock.json")
    text = text.replace(
        "        working-directory: tools/video_renderer\n",
        f"        working-directory: {SOURCE_DIR}/tools/video_renderer\n")
    text = text.replace("          path: dist/\n", f"          path: {SOURCE_DIR}/dist/\n")
    text = re.sub(r"^(            )dist/", rf"\1{SOURCE_DIR}/dist/", text, flags=re.MULTILINE)
    return text


def build(source_text: str | None = None) -> str:
    text = source_text if source_text is not None else SOURCE.read_text(encoding="utf-8")

    # The shell repository has no code of its own: the private checkout replaces
    # the usual "Checkout repository" step.
    text = text.replace("      - name: Checkout repository\n        uses: actions/checkout@v4\n",
                        CHECKOUT)

    # One job-level default so every `run:` block already lives in src/.
    text = text.replace("    timeout-minutes: 360\n",
                        "    timeout-minutes: 360\n" + DEFAULTS, 1)

    text = _prefix_paths(text)
    return BANNER + text


def main() -> int:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(build(), encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)} ({len(TARGET.read_text().splitlines())} lines).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
